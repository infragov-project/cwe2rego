# chef_redis_unencrypted.rb
# A Chef recipe to configure Redis without TLS in transit.

package 'redis-server' do
  action :install
end

service 'redis-server' do
  action [:enable, :start]
end

file '/etc/redis/redis.conf' do
  content '# This file was generated by Chef
port 6379
bind 0.0.0.0
# Explicitly disabling TLS related features
tls-port 0 # Do not listen on a TLS-enabled port
tls-replication no # Do not use TLS for replication
tls-auth-clients no # Do not require client certificates for TLS
tls_enabled no # Hypothetical, explicit flag for disabling TLS
requirepass insecurepassword
'
  mode '0644'
  notifies :restart, 'service[redis-server]', :delayed
end
